def add_md_to_doc(doc: Document, md: str) -> None:
    for raw_line in md.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("# "):
            doc.add_heading(line[2:], level=0)
        elif line.startswith("## "):
            doc.add_heading(line[3:], level=1)
        elif line.startswith("### "):
            doc.add_heading(line[4:], level=2)
        elif line.startswith("- "):
            doc.add_paragraph(line[2:], style="List Bullet")
        else:
            doc.add_paragraph(line)


def build_docx(md: str) -> None:
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Inches(0.8)
    section.bottom_margin = Inches(0.8)
    section.left_margin = Inches(0.8)
    section.right_margin = Inches(0.8)
    styles = doc.styles
    styles["Normal"].font.name = "Arial"
    styles["Normal"].font.size = Pt(10.5)
    styles["Normal"].paragraph_format.space_after = Pt(6)
    add_md_to_doc(doc, md)

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    doc.add_heading("Figures", level=1)
    for figure, caption in [
        (
            FIGURES / "dataset_overview.png",
            "Figure 1. Dataset register and local data audit.",
        ),
        (
            FIGURES / "kuppe_visium_celltype_overview.png",
            "Figure 2. Human myocardial infarction Visium cell-type composition.",
        ),
    ]:
        if figure.exists():
            doc.add_picture(str(figure), width=Inches(6.5))
            doc.add_paragraph(caption)

    out = SUBMISSION / "preprint_manuscript.docx"
    doc.save(out)
    print(f"Wrote {out}")


