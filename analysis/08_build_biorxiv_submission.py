def read_summary_values() -> dict[str, str]:
    summary = pd.read_csv(TABLES / "kuppe_visium_celltype_summary.csv")
    rows = {}
    for zone in ["Control", "Remote zone", "Fibrotic zone", "Infarct zone"]:
        zone_df = summary[summary["zone_label"] == zone].sort_values(
            "dominant_fraction", ascending=False
        )
        top = zone_df.iloc[0]
        rows[zone] = (
            f"{top['cell_type']} dominant spots "
            f"({top['dominant_fraction'] * 100:.1f}%; {int(top['dominant_spots'])}/"
            f"{int(top['n_spots'])})"
        )
    return rows


